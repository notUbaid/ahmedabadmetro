export const getStationName = (station: Station | undefined | null, lang: Language = 'en'): string => {
  if (!station) return '';
  if (lang === 'gu' && station.nameGu) {
    return station.nameGu;
  }
  if (lang === 'hi' && station.nameHi) {
    return station.nameHi;
  }
  return station.name;
};
